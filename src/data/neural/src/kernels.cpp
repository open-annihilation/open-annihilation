constexpr int64_t k_wide_min = -9223372036854775807LL - 1;
constexpr int64_t k_wide_max = 9223372036854775807LL;

/// Adds two int64 values and holds the sum to int16.
///
/// A sum that does not fit in int64 is outside the int16 range, so it is held
/// to the limit of its sign.
///
/// @param left the first value
/// @param right the second value
/// @return the sum, held to int16
int16_t held_sum(int64_t left, int64_t right) noexcept {
    const bool overflow =
        (right > 0 && left > k_wide_max - right) || (right < 0 && left < k_wide_min - right);
    if (overflow)
        return right > 0 ? static_cast<int16_t>(32767) : static_cast<int16_t>(-32768);
    return saturate_int16(left + right);
}

// The three tables, generated by tests/tables_reference.py. Do not edit them.
#include "tables.inc"

/// The table index clamp(scaled + 2048, 0, 4095), without a sum that overflows.
///
/// @param scaled R(x, exponent, -8)
/// @return an index from 0 to 4095
int32_t table_index(int64_t scaled) noexcept {
    if (scaled > 2047)
        return 4095;
    if (scaled < -2048)
        return 0;
    return static_cast<int32_t>(scaled + 2048);
}

/// The exponent-table term for one distance from the largest softmax input.
///
/// A distance above 4095 is 0. The largest input has distance 0, so a negative
/// distance does not arise; it reads the same entry as 0.
///
/// @param distance R(peak - value, exponent, -8)
/// @return the table term, or 0
uint32_t exponent_term(int64_t distance) noexcept {
    if (distance > 4095)
        return 0;
    if (distance < 0)
        return exp_table[0];
    return exp_table[static_cast<std::size_t>(distance)];
}

