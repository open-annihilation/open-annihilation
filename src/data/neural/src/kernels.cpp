template <typename Weight>
void conv2d(
    std::span<const int16_t> input,
    const std::array<uint32_t, 4>& input_dims,
    std::span<const Weight> weights,
    std::span<const int32_t> bias,
    std::span<int16_t> output,
    const std::array<uint32_t, 4>& output_dims,
    uint8_t kernel_h,
    uint8_t kernel_w,
    uint8_t stride_h,
    uint8_t stride_w,
    uint8_t pad_h,
    uint8_t pad_w,
    int32_t input_exponent,
    int32_t weight_exponent,
    int32_t output_exponent
) noexcept {
    const uint32_t channels = input_dims[0];
    const uint32_t height = input_dims[1];
    const uint32_t width = input_dims[2];
    const uint32_t kernels = output_dims[0];
    const uint32_t out_height = output_dims[1];
    const uint32_t out_width = output_dims[2];
    const int32_t sum_exponent = input_exponent + weight_exponent;
    const int32_t window_h = static_cast<int32_t>(kernel_h);
    const int32_t window_w = static_cast<int32_t>(kernel_w);
    const int32_t step_h = static_cast<int32_t>(stride_h);
    const int32_t step_w = static_cast<int32_t>(stride_w);
    const int32_t margin_h = static_cast<int32_t>(pad_h);
    const int32_t margin_w = static_cast<int32_t>(pad_w);
    for (uint32_t kernel = 0; kernel < kernels; ++kernel) {
        const int64_t base = bias.empty() ? int64_t{0} : static_cast<int64_t>(bias[kernel]);
        for (uint32_t out_y = 0; out_y < out_height; ++out_y) {
            for (uint32_t out_x = 0; out_x < out_width; ++out_x) {
                int64_t sum = base;
                const int32_t origin_y = static_cast<int32_t>(out_y) * step_h - margin_h;
                const int32_t origin_x = static_cast<int32_t>(out_x) * step_w - margin_w;
                for (uint32_t channel = 0; channel < channels; ++channel) {
                    for (int32_t kernel_y = 0; kernel_y < window_h; ++kernel_y) {
                        const int32_t in_y = origin_y + kernel_y;
                        for (int32_t kernel_x = 0; kernel_x < window_w; ++kernel_x) {
                            const int32_t in_x = origin_x + kernel_x;
                            if (in_y < 0 || in_x < 0 || static_cast<uint32_t>(in_y) >= height ||
                                static_cast<uint32_t>(in_x) >= width)
                                continue;
                            const std::size_t sample_at =
                                (static_cast<std::size_t>(channel) * height +
                                 static_cast<std::size_t>(in_y)) *
                                    width +
                                static_cast<std::size_t>(in_x);
                            const std::size_t weight_at =
                                ((static_cast<std::size_t>(kernel) * channels + channel) *
                                     kernel_h +
                                 static_cast<std::size_t>(kernel_y)) *
                                    kernel_w +
                                static_cast<std::size_t>(kernel_x);
                            const int64_t sample = input[sample_at];
                            const int64_t weight = weights[weight_at];
                            sum += sample * weight;
                        }
                    }
                }
                const std::size_t out_at =
                    (static_cast<std::size_t>(kernel) * out_height + out_y) * out_width + out_x;
                output[out_at] = saturate_int16(rescale(sum, sum_exponent, output_exponent));
            }
        }
    }
}

void maxpool(
    std::span<const int16_t> input,
    const std::array<uint32_t, 4>& input_dims,
    std::span<int16_t> output,
    const std::array<uint32_t, 4>& output_dims,
    uint8_t kernel_h,
    uint8_t kernel_w,
    uint8_t stride_h,
    uint8_t stride_w
) noexcept {
    const uint32_t channels = input_dims[0];
    const uint32_t height = input_dims[1];
    const uint32_t width = input_dims[2];
    const uint32_t out_height = output_dims[1];
    const uint32_t out_width = output_dims[2];
    for (uint32_t channel = 0; channel < channels; ++channel) {
        for (uint32_t out_y = 0; out_y < out_height; ++out_y) {
            for (uint32_t out_x = 0; out_x < out_width; ++out_x) {
                const uint32_t origin_y = out_y * stride_h;
                const uint32_t origin_x = out_x * stride_w;
                int16_t best = input
                    [(static_cast<std::size_t>(channel) * height + origin_y) * width + origin_x];
                for (uint32_t kernel_y = 0; kernel_y < kernel_h; ++kernel_y) {
                    for (uint32_t kernel_x = 0; kernel_x < kernel_w; ++kernel_x) {
                        const uint32_t in_y = origin_y + kernel_y;
                        const uint32_t in_x = origin_x + kernel_x;
                        const int16_t sample = input
                            [(static_cast<std::size_t>(channel) * height + in_y) * width + in_x];
                        if (sample > best)
                            best = sample;
                    }
                }
                output
                    [(static_cast<std::size_t>(channel) * out_height + out_y) * out_width + out_x] =
                        best;
            }
        }
    }
}

void tanh(
    std::span<const int16_t> input, std::span<int16_t> output, int32_t input_exponent
) noexcept {
    const std::size_t count = input.size();
    for (std::size_t element = 0; element < count; ++element) {
        const int64_t scaled = rescale(input[element], input_exponent, -8);
        output[element] = tanh_table[static_cast<std::size_t>(table_index(scaled))];
    }
}

