# Integer tables for tanh, sigmoid and the softmax exponent. Run with:
#   python3 -I src/data/neural/tests/tables_reference.py
# The stdout is src/data/neural/src/tables.inc, byte for byte. That file is
# this script's output and is never edited by hand.
#
# Each entry is rounded half to even with decimal arithmetic at 50 digits
# (decimal.Context(prec=50) and Decimal.exp), which is the same on every
# machine. The runner does not compute these values.

import hashlib
import sys
from decimal import ROUND_HALF_EVEN, Context, Decimal

TABLE_LENGTH = 4096
CENTRE = 2048
STEP = 256
CONTEXT = Context(prec=50)
SPOTS = (0, 1, 2047, 2048, 2049, 4094, 4095)

_TABLES = None


def round_half_even(value):
    """Rounds a Decimal to an integer, halves to even."""
    return int(value.to_integral_value(rounding=ROUND_HALF_EVEN, context=CONTEXT))


def hold(value, low, high):
    """Holds an integer to a closed range."""
    if value < low:
        return low
    if value > high:
        return high
    return value


def _compute():
    """Builds the three tables. The argument of each exponent is exact."""
    tanh_values = []
    sigmoid_values = []
    exp_values = []
    one = Decimal(1)
    scale = Decimal(32768)
    exp_scale = Decimal(1 << 30)
    for index in range(TABLE_LENGTH):
        z = (Decimal(index) - Decimal(CENTRE)) / Decimal(STEP)
        doubled = CONTEXT.exp(z * 2)
        tanh_raw = round_half_even(((doubled - one) / (doubled + one)) * scale)
        tanh_values.append(hold(tanh_raw, -32768, 32767))
        sigmoid_raw = round_half_even(scale / (one + CONTEXT.exp(-z)))
        sigmoid_values.append(hold(sigmoid_raw, 0, 32767))
        exp_raw = round_half_even(exp_scale * CONTEXT.exp(-Decimal(index) / Decimal(STEP)))
        if exp_raw < 0 or exp_raw > 0xFFFFFFFF:
            raise RuntimeError(f"exp[{index}] = {exp_raw} does not fit in uint32")
        exp_values.append(exp_raw)
    return tanh_values, sigmoid_values, exp_values


def tables():
    """Returns (tanh, sigmoid, exp), each a list of 4096 integers."""
    global _TABLES
    if _TABLES is None:
        _TABLES = _compute()
    return _TABLES


def tanh_table():
    """Returns the 4096 tanh entries, held to int16."""
    return tables()[0]


def sigmoid_table():
    """Returns the 4096 sigmoid entries, held to 0..32767."""
    return tables()[1]


def exp_table():
    """Returns the 4096 exponent entries, each a uint32."""
    return tables()[2]


def little_endian(values, width):
    """Packs integers as little-endian words of `width` bytes."""
    raw = bytearray()
    for value in values:
        word = value & ((1 << (width * 8)) - 1)
        for shift in range(width):
            raw.append((word >> (8 * shift)) & 0xFF)
    return bytes(raw)


def sha256_hex(values, width):
    """Returns the SHA-256 hex of the little-endian bytes."""
    return hashlib.sha256(little_endian(values, width)).hexdigest()


def format_array(cpp_type, name, values):
    """Formats one constexpr array, 16 values a line."""
    lines = [f"constexpr std::array<{cpp_type}, {len(values)}> {name} = {{"]
    for start in range(0, len(values), 16):
        chunk = values[start : start + 16]
        text = ", ".join(str(value) for value in chunk)
        if start + 16 < len(values):
            text += ","
        lines.append(f"    {text}")
    lines.append("};")
    return "\n".join(lines)


def spot_text(values):
    """Formats the seven pinned entries."""
    return " ".join(str(values[index]) for index in SPOTS)


def render():
    """Returns the whole tables.inc text, including the trailing newline."""
    tanh_values, sigmoid_values, exp_values = tables()
    parts = [
        "// SPDX-FileCopyrightText: The Open Annihilation Authors; see COPYRIGHT",
        "// SPDX-License-Identifier: GPL-3.0-only",
        "",
        "// Generated by src/data/neural/tests/tables_reference.py.",
        "// This file is that script's output and is never edited by hand.",
        "",
        format_array("int16_t", "tanh_table", tanh_values),
        "",
        format_array("int16_t", "sigmoid_table", sigmoid_values),
        "",
        format_array("uint32_t", "exp_table", exp_values),
        "",
        "// Little-endian SHA-256 of each table. The test pins these lines.",
        f"// tanh {sha256_hex(tanh_values, 2)}",
        f"// sigmoid {sha256_hex(sigmoid_values, 2)}",
        f"// exp {sha256_hex(exp_values, 4)}",
        "// Entries at 0, 1, 2047, 2048, 2049, 4094, 4095.",
        f"// tanh {spot_text(tanh_values)}",
        f"// sigmoid {spot_text(sigmoid_values)}",
        f"// exp {spot_text(exp_values)}",
        "",
    ]
    return "\n".join(parts)


def main():
    half = Decimal("0.5")
    if round_half_even(Decimal(1) + half) != 2 or round_half_even(Decimal(2) + half) != 2:
        print("half-to-even rounding is wrong", file=sys.stderr)
        sys.exit(1)
    tanh_values, sigmoid_values, exp_values = tables()
    if tanh_values[2048] != 0 or sigmoid_values[2048] != 16384 or exp_values[0] != (1 << 30):
        print("centre entries are wrong", file=sys.stderr)
        sys.exit(1)
    sys.stdout.write(render())


if __name__ == "__main__":
    main()
