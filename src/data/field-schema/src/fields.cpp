std::span<const FieldSpec> fields(RecordKind record) noexcept {
    const FieldSpec* begin = nullptr;
    std::size_t count = 0;
    for (const FieldSpec& spec : k_fields) {
        if (spec.record != record)
            continue;
        if (begin == nullptr)
            begin = &spec;
        ++count;
    }
    if (begin == nullptr)
        return {};
    return {begin, count};
}

const FieldSpec* find_field(RecordKind record, std::string_view key) noexcept {
    if (record == RecordKind::weapon_damage) {
        const FieldSpec* wildcard = nullptr;
        for (const FieldSpec& spec : fields(record)) {
            if (spec.key == "default") {
                if (same_key(key, "default"))
                    return &spec;
            } else if (spec.key.empty()) {
                wildcard = &spec;
            }
        }
        return wildcard;
    }
    for (const FieldSpec& spec : fields(record))
        if (same_key(spec.key, key))
            return &spec;
    return nullptr;
}

