constexpr std::size_t count_of(RecordKind record) noexcept {
    std::size_t count = 0;
    for (const FieldSpec& spec : k_fields)
        if (spec.record == record)
            ++count;
    return count;
}

static_assert(count_of(RecordKind::unit) == 120);
static_assert(count_of(RecordKind::weapon) == 73);
static_assert(count_of(RecordKind::weapon_damage) == 2);
static_assert(count_of(RecordKind::move_class) == 9);

bool same_key(std::string_view left, std::string_view right) noexcept {
    if (left.size() != right.size())
        return false;
    for (std::size_t index = 0; index < left.size(); ++index) {
        unsigned char lhs = static_cast<unsigned char>(left[index]);
        unsigned char rhs = static_cast<unsigned char>(right[index]);
        if (lhs >= 'A' && lhs <= 'Z')
            lhs = static_cast<unsigned char>(lhs + 32);
        if (rhs >= 'A' && rhs <= 'Z')
            rhs = static_cast<unsigned char>(rhs + 32);
        if (lhs != rhs)
            return false;
    }
    return true;
}

