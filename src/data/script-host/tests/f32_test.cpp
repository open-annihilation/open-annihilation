void read_text(void* context, lua_State* state, int results) {
    auto* out = static_cast<std::string*>(context);
    if (results == 1 && lua_type(state, -1) == LUA_TSTRING && lua_tostring(state, -1) != nullptr)
        *out = lua_tostring(state, -1);
}

void run_lua() {
    const std::string golden = golden_script();
    Package package;
    host::ScriptError error;
    auto sandbox = open_box(package, error, f32_profile());
    if (!sandbox)
        return;
    if (!run_source(*sandbox, package, golden, error)) {
        std::fprintf(
            stderr, "golden lua line %d: %s\n", static_cast<int>(error.line), error.message.c_str()
        );
        OA_CHECK(false);
    }

    Package behaviour_package;
    host::ScriptError behaviour_error;
    auto behaviour = open_box(behaviour_package, behaviour_error, f32_profile());
    if (!behaviour)
        return;
    if (!run_source(*behaviour, behaviour_package, behaviour_source(), behaviour_error)) {
        std::fprintf(
            stderr,
            "behaviour line %d: %s\n",
            static_cast<int>(behaviour_error.line),
            behaviour_error.message.c_str()
        );
        OA_CHECK(false);
    }
}

bool signaling_nan(uint32_t bits) {
    const uint32_t magnitude = bits & 0x7fffffffu;
    return magnitude > 0x7f800000u && (magnitude & 0x00400000u) == 0;
}

void trip_values(void*, lua_State* state) {
    const uint32_t samples[] = {
        0,
        0x80000000u,
        0x3f800000u,
        0xbf800000u,
        0x00000001u,
        0x7f800000u,
        0xff800000u,
        0x7fc00000u,
        0x00800000u,
        0x7f7fffffu,
        0x33800000u,
        0x4b800000u
    };
    for (const uint32_t bits : samples) {
        if (signaling_nan(bits))
            continue;
        const float value = float_of(bits);
        host::push_f32(state, value);
        float got = 0;
        if (!host::to_f32(state, -1, &got)) {
            luaL_error(state, "to_f32 rejected an f32");
            return;
        }
        uint32_t out = 0;
        std::memcpy(&out, &got, sizeof out);
        if (out != bits) {
            luaL_error(state, "push/to bits changed");
            return;
        }
        lua_pop(state, 1);
    }
    float sentinel = 42;
    lua_pushinteger(state, 1);
    if (host::to_f32(state, -1, &sentinel)) {
        luaL_error(state, "to_f32 accepted an integer");
        return;
    }
    if (sentinel != 42.0f) {
        luaL_error(state, "to_f32 changed the out value");
        return;
    }
    lua_pop(state, 1);
}

void round_trip_push() {
    Package package;
    host::ScriptError error;
    auto sandbox = open_box(package, error, f32_profile());
    if (!sandbox)
        return;
    if (!sandbox->run_host("host", nullptr, trip_values, error)) {
        std::fprintf(stderr, "push/to: %s\n", error.message.c_str());
        OA_CHECK(false);
    }
}

void mutator_has_no_f32() {
    Package package;
    host::ScriptError error;
    auto sandbox = open_box(package, error, host::mutator_profile());
    if (!sandbox)
        return;
    std::string shown;
    host::CallHooks hooks;
    hooks.context = &shown;
    hooks.read = read_text;
    const std::string source = "return type(f32)\n";
    package.files["mutator.lua"] = std::vector<uint8_t>(source.begin(), source.end());
    if (!sandbox->run_file("mutator.lua", "plan", &hooks, error)) {
        std::fprintf(stderr, "mutator: %s\n", error.message.c_str());
        OA_CHECK(false);
        return;
    }
    OA_CHECK(shown == "nil");
}

