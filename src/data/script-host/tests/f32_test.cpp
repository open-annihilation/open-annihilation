bool hex_bits(const char* text, uint32_t* bits) {
    if (text == nullptr || std::strlen(text) != 8)
        return false;
    const char* end = text + 8;
    const std::from_chars_result parsed = std::from_chars(text, end, *bits, 16);
    return parsed.ec == std::errc{} && parsed.ptr == end;
}

bool decimal(const char* text, int64_t* value) {
    if (text == nullptr || text[0] == '\0')
        return false;
    const char* end = text + std::strlen(text);
    const std::from_chars_result parsed = std::from_chars(text, end, *value);
    return parsed.ec == std::errc{} && parsed.ptr == end;
}

uint32_t bits_of(float value) {
    uint32_t bits = 0;
    std::memcpy(&bits, &value, sizeof bits);
    if ((bits & 0x7fffffffu) > 0x7f800000u)
        return 0x7fc00000u;
    return bits;
}

float float_of(uint32_t bits) {
    float value = 0;
    std::memcpy(&value, &bits, sizeof value);
    return value;
}

int hex_value(char digit) {
    if (digit >= '0' && digit <= '9')
        return digit - '0';
    if (digit >= 'a' && digit <= 'f')
        return digit - 'a' + 10;
    if (digit >= 'A' && digit <= 'F')
        return digit - 'A' + 10;
    return -1;
}

/// Reads one exact hexadecimal double. The tokens are the reference's own.
bool double_from_hex(const char* text, double* out) {
    const char* cursor = text;
    bool negative = false;
    if (*cursor == '-') {
        negative = true;
        ++cursor;
    }
    if (cursor[0] != '0' || (cursor[1] != 'x' && cursor[1] != 'X'))
        return false;
    cursor += 2;
    uint64_t significand = 0;
    int extra_exponent = 0;
    int digits = 0;
    bool dot = false;
    while (*cursor != '\0' && *cursor != 'p' && *cursor != 'P') {
        if (*cursor == '.') {
            if (dot)
                return false;
            dot = true;
            ++cursor;
            continue;
        }
        const int nibble = hex_value(*cursor);
        if (nibble < 0 || significand > (UINT64_MAX >> 4))
            return false;
        significand = (significand << 4) | static_cast<uint64_t>(nibble);
        if (dot)
            extra_exponent -= 4;
        ++digits;
        ++cursor;
    }
    if (digits == 0 || (*cursor != 'p' && *cursor != 'P'))
        return false;
    ++cursor;
    bool exponent_negative = false;
    if (*cursor == '+')
        ++cursor;
    else if (*cursor == '-') {
        exponent_negative = true;
        ++cursor;
    }
    if (*cursor < '0' || *cursor > '9')
        return false;
    int exponent = 0;
    while (*cursor >= '0' && *cursor <= '9') {
        exponent = exponent * 10 + (*cursor - '0');
        ++cursor;
    }
    if (*cursor != '\0')
        return false;
    if (exponent_negative)
        exponent = -exponent;
    exponent += extra_exponent;
    if (significand == 0) {
        *out = negative ? -0.0 : 0.0;
        return true;
    }
    const int log_bit = 63 - std::countl_zero(significand);
    const int unbiased = log_bit + exponent;
    if (unbiased > 1023) {
        *out = negative ? -std::numeric_limits<double>::infinity()
                        : std::numeric_limits<double>::infinity();
        return true;
    }
    if (unbiased >= -1022) {
        uint64_t magnitude = significand;
        if (log_bit > 52) {
            const int shift = log_bit - 52;
            if ((magnitude & ((uint64_t{1} << shift) - 1)) != 0)
                return false;
            magnitude >>= static_cast<unsigned>(shift);
        } else if (log_bit < 52) {
            magnitude <<= static_cast<unsigned>(52 - log_bit);
        }
        uint64_t encoded = (static_cast<uint64_t>(unbiased + 1023) << 52) |
                           (magnitude & ((uint64_t{1} << 52) - 1));
        if (negative)
            encoded |= uint64_t{1} << 63;
        std::memcpy(out, &encoded, sizeof *out);
        return true;
    }
    const int shift = exponent + 1074;
    if (shift >= 64 || shift <= -64)
        return false;
    uint64_t magnitude = 0;
    if (shift >= 0)
        magnitude = significand << static_cast<unsigned>(shift);
    else {
        const int dropped = -shift;
        if ((significand & ((uint64_t{1} << dropped) - 1)) != 0)
            return false;
        magnitude = significand >> static_cast<unsigned>(dropped);
    }
    if (negative)
        magnitude |= uint64_t{1} << 63;
    std::memcpy(out, &magnitude, sizeof *out);
    return true;
}

bool double_from_token(const char* text, double* out) {
    if (std::strcmp(text, "0") == 0 || std::strcmp(text, "0.0") == 0) {
        *out = 0.0;
        return true;
    }
    if (std::strcmp(text, "-0") == 0 || std::strcmp(text, "-0.0") == 0) {
        *out = -0.0;
        return true;
    }
    if (std::strcmp(text, "inf") == 0) {
        *out = std::numeric_limits<double>::infinity();
        return true;
    }
    if (std::strcmp(text, "-inf") == 0) {
        *out = -std::numeric_limits<double>::infinity();
        return true;
    }
    if (std::strcmp(text, "nan") == 0) {
        *out = std::numeric_limits<double>::quiet_NaN();
        return true;
    }
    return double_from_hex(text, out);
}

void expect_bits(const Golden& row, uint32_t got) {
    uint32_t want = 0;
    if (!hex_bits(row.result, &want) || got != want) {
        char spelled[16];
        std::snprintf(spelled, sizeof spelled, "%08x", got);
        report_row(row, spelled);
        OA_CHECK(false);
    }
}

float operate(const char* op, float left, float right) {
    const std::string_view kind = op;
    if (kind == "sub")
        return left - right;
    if (kind == "mul")
        return left * right;
    if (kind == "div")
        return left / right;
    return left + right;
}

void check_rows() {
    int arithmetic = 0;
    int integers = 0;
    int doubles = 0;
    int fixed_counts = 0;
    int to_fixed = 0;
    for (const Golden& row : k_rows) {
        const std::string_view op = row.op;
        if (op == "add" || op == "sub" || op == "mul" || op == "div") {
            uint32_t left_bits = 0;
            uint32_t right_bits = 0;
            OA_CHECK(hex_bits(row.left, &left_bits));
            OA_CHECK(hex_bits(row.right, &right_bits));
            const float value = operate(row.op, float_of(left_bits), float_of(right_bits));
            expect_bits(row, bits_of(value));
            ++arithmetic;
            continue;
        }
        if (op == "i64") {
            int64_t number = 0;
            OA_CHECK(decimal(row.left, &number));
            expect_bits(row, bits_of(host::f32_from_integer(number)));
            ++integers;
            continue;
        }
        if (op == "f64") {
            double number = 0;
            if (!double_from_token(row.left, &number)) {
                report_row(row, "token");
                OA_CHECK(false);
                continue;
            }
            expect_bits(row, bits_of(host::f32_from_double(number)));
            ++doubles;
            continue;
        }
        if (op == "fixed") {
            int64_t count = 0;
            OA_CHECK(decimal(row.left, &count));
            expect_bits(row, bits_of(host::f32_from_fixed_count(count)));
            ++fixed_counts;
            continue;
        }
        if (op == "tofixed") {
            uint32_t stored = 0;
            OA_CHECK(hex_bits(row.left, &stored));
            const std::optional<int64_t> count = host::f32_to_fixed_count(float_of(stored));
            if (std::strcmp(row.result, "error") == 0) {
                if (count.has_value()) {
                    report_row(row, "succeeded");
                    OA_CHECK(false);
                }
            } else {
                int64_t want = 0;
                if (!count.has_value() || !decimal(row.result, &want) || *count != want) {
                    report_row(row, "mismatch");
                    OA_CHECK(false);
                }
            }
            ++to_fixed;
            continue;
        }
        report_row(row, "unknown");
        OA_CHECK(false);
    }
    OA_CHECK(arithmetic >= 200);
    OA_CHECK(integers >= 60);
    OA_CHECK(doubles >= 40);
    OA_CHECK(fixed_counts >= 40);
    OA_CHECK(to_fixed >= 40);

    const int64_t above = (int64_t{1} << 60) + (int64_t{1} << 37) + (int64_t{1} << 36) - 1;
    OA_CHECK(bits_of(host::f32_from_integer(above)) == 0x5d800001u);
    OA_CHECK(bits_of(host::f32_from_integer(16777217)) == 0x4b800000u);
    OA_CHECK(bits_of(host::f32_from_integer(std::numeric_limits<int64_t>::min())) == 0xdf000000u);
    OA_CHECK(bits_of(host::f32_from_fixed_count(1)) == 0x37800000u);
    OA_CHECK(host::f32_to_fixed_count(1.0f) == std::optional<int64_t>{65536});
    OA_CHECK(!host::f32_to_fixed_count(std::numeric_limits<float>::infinity()).has_value());
    OA_CHECK(!host::f32_to_fixed_count(std::numeric_limits<float>::quiet_NaN()).has_value());
    const uint32_t two_47_bits = (47u + 127u) << 23;
    OA_CHECK(!host::f32_to_fixed_count(float_of(two_47_bits)).has_value());
}

std::string golden_script() {
    std::string source =
        "local function fail(detail) error(detail, 0) end\n"
        "local function integer(text)\n"
        "  local n = math.tointeger(text)\n"
        "  if n == nil then fail('not an integer: ' .. text) end\n"
        "  return n\n"
        "end\n"
        "local function bits(text)\n"
        "  return integer('0x' .. text)\n"
        "end\n"
        "local function number_value(text)\n"
        "  if text == 'inf' then return math.huge end\n"
        "  if text == '-inf' then return -math.huge end\n"
        "  if text == 'nan' then return 0/0 end\n"
        "  if text == '-0' or text == '-0.0' then return -0.0 end\n"
        "  if text == '0' or text == '0.0' then return 0.0 end\n"
        "  local n = tonumber(text)\n"
        "  if n == nil then fail('not a number: ' .. text) end\n"
        "  return n\n"
        "end\n"
        "local function check(op, a, b, result)\n"
        "  local function run()\n"
        "    if op == 'add' then return (f32.from_bits(bits(a)) + f32.from_bits(bits(b))):bits() "
        "end\n"
        "    if op == 'sub' then return (f32.from_bits(bits(a)) - f32.from_bits(bits(b))):bits() "
        "end\n"
        "    if op == 'mul' then return (f32.from_bits(bits(a)) * f32.from_bits(bits(b))):bits() "
        "end\n"
        "    if op == 'div' then return (f32.from_bits(bits(a)) / f32.from_bits(bits(b))):bits() "
        "end\n"
        "    if op == 'i64' then return f32(integer(a)):bits() end\n"
        "    if op == 'f64' then return f32(number_value(a)):bits() end\n"
        "    if op == 'fixed' then return f32(fixed.raw(integer(a))):bits() end\n"
        "    if op == 'tofixed' then return f32.from_bits(bits(a)):tofixed():raw() end\n"
        "    fail('unknown ' .. op)\n"
        "  end\n"
        "  if result == 'error' then\n"
        "    local ok = pcall(run)\n"
        "    if ok then fail(op .. ' ' .. a .. ' succeeded') end\n"
        "    return\n"
        "  end\n"
        "  local ok, got = pcall(run)\n"
        "  if not ok then fail(op .. ' ' .. a .. ' ' .. tostring(got)) end\n"
        "  local want = bits(result)\n"
        "  if op == 'tofixed' then want = integer(result) end\n"
        "  if got ~= want then\n"
        "    fail(op .. ' ' .. a .. ' got ' .. tostring(got) .. ' want ' .. tostring(want))\n"
        "  end\n"
        "end\n";
    source.reserve(source.size() + sizeof k_rows / sizeof k_rows[0] * 80);
    for (const Golden& row : k_rows) {
        source += "check(\"";
        source += row.op;
        source += "\", \"";
        source += row.left;
        source += "\", \"";
        source += row.right;
        source += "\", \"";
        source += row.result;
        source += "\")\n";
    }
    source += "return true\n";
    return source;
}

void append_round_trips(std::string& source) {
    source +=
        "local function round_trip(n)\n"
        "  local got = f32.from_bits(n):bits()\n"
        "  if got ~= n then error('bits ' .. tostring(n) .. ' got ' .. tostring(got), 0) end\n"
        "end\n";
    int written = 0;
    const auto append_one = [&](uint32_t pattern) {
        source += "round_trip(";
        source += std::to_string(pattern);
        source += ")\n";
        ++written;
    };
    for (uint32_t step = 0; step < 80; ++step) {
        append_one(step);
        append_one(step << 8);
        append_one(step << 16);
        append_one(0x7f800000u + step);
        append_one(0x80000000u | (step << 20));
    }
    append_one(0x7fc00000u);
    append_one(0xffc00000u);
    append_one(0x7fffffffu);
    append_one(0xffffffffu);
    append_one(0x7f800001u);
    append_one(0xff800001u);
    OA_CHECK(written >= 300);
}

