def self_test():
    failures = []
    chord_case(failures)
    try:
        base = oamod_yaml.load_file(REGISTRY)
        hack_ids, pads, touch_enums = load_references()
    except (RegistryError, oamod_yaml.OamodYamlError, OSError) as error:
        print(f"FAIL registry could not be read: {error}")
        print("gen_input_actions self-test: 1 failures")
        return 1
    good = check_registry(base, hack_ids, pads, touch_enums)
    if good:
        failures.append("good registry: " + " | ".join(good[:12]))

    def rule2(reg):
        body = copy.deepcopy(reg["actions"]["order.attack"])
        body.pop("gadget", None)
        body.pop("pad", None)
        body.pop("touch", None)
        body["order"] = 900
        reg["actions"]["gui.stolen"] = body

