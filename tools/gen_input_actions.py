def cxx_string(text):
    out = ['"']
    for character in text:
        if character == "\\":
            out.append("\\\\")
        elif character == '"':
            out.append('\\"')
        elif 32 <= ord(character) <= 126:
            out.append(character)
        else:
            out.append("\\u%04x" % ord(character))
    out.append('"')
    return "".join(out)


def snake(name):
    return name.replace("-", "_").replace(".", "_")


def bits(names, index):
    value = 0
    for name in names:
        if name in index:
            value |= 1 << index[name]
    return value


def emit_string_array(lines, name, items):
    if not items:
        return None
    values = ", ".join(cxx_string(item) for item in items)
    lines.append(f"constexpr std::string_view {name}[]{{{values}}};\n")
    return name


def span_of(array_name):
    if array_name is None:
        return "std::span<const std::string_view>{}"
    return f"std::span<const std::string_view>({array_name})"


def kind_of(kind):
    return "Kind::" + kind


def by_of(by):
    return "By::" + (by if by else "none")


def target_of(target):
    if not target:
        return "Target::none"
    return "Target::" + target.replace("-", "_")


def bool_of(value):
    return "true" if value else "false"


def generate_text(reg):
    context_index = {name: index for index, (name, _parent, _overlay, _title) in enumerate(CONTEXTS)}
    condition_index = {name: index for index, name in enumerate(CONDITION_NAMES)}
    lines = [GENERATED]
    lines.append("constexpr Context k_contexts[]{\n")
    for name, parent, overlay, title in CONTEXTS:
        parent_text = "uint8_t{255}" if parent is None else f"uint8_t{{{context_index[parent]}}}"
        lines.append(f"    {{{cxx_string(name)}, {parent_text}, {bool_of(overlay)}, "
                     f"{cxx_string(title)}}},\n")
    lines.append("};\n\n")
    condition_values = ", ".join(cxx_string(name) for name in CONDITION_NAMES)
    lines.append(f"constexpr std::string_view k_conditions[]{{{condition_values}}};\n\n")
    exclusive_text = ", ".join(
        "{uint8_t{%d}, uint8_t{%d}}" % (condition_index[pair[0]], condition_index[pair[1]])
        for pair in EXCLUSIVE_PAIRS)
    lines.append(f"constexpr ExclusivePair k_exclusive[]{{{exclusive_text}}};\n\n")
    lines.append("constexpr Area k_areas[]{\n")
    for index, (name, title) in enumerate(AREAS, start=1):
        lines.append(f"    {{{cxx_string(name)}, uint16_t{{{index}}}, {cxx_string(title)}}},\n")
    lines.append("};\n\n")

    families = reg["families"]
    for family_id, body in families.items():
        emit_string_array(lines, snake(family_id) + "_source", body["source"])
    lines.append("constexpr Family k_families[]{\n")
    for family_id, body in families.items():
        panel = body.get("order-panel") or {}
        panel_area = panel.get("area", "")
        panel_context = bits(panel.get("context", []), context_index) if panel else 0
        template = body.get("default-template", "")
        lines.append(
            "    {" + ", ".join([
                cxx_string(family_id),
                cxx_string(body["area"]),
                f"uint32_t{{{bits(body['context'], context_index)}}}",
                kind_of(body["kind"]),
                by_of(body["by"]),
                span_of(snake(family_id) + "_source"),
                cxx_string(template) if template else "std::string_view{}",
                cxx_string(panel_area) if panel_area else "std::string_view{}",
                f"uint32_t{{{panel_context}}}",
            ]) + "},\n")
    lines.append("};\n\n")

    hack_names = set()
    for body in reg["actions"].values():
        for item in body.get("source", []):
            if item not in PLAIN_SOURCES:
                hack_names.add(item)
        for hack_id in body.get("hacks", {}):
            hack_names.add(hack_id)
    hack_names = sorted(hack_names)
    values = ", ".join(cxx_string(name) for name in hack_names)
    lines.append(f"constexpr std::string_view k_hack_ids[]{{{values}}};\n\n")

    parsed = []
    for action_id, body in reg["actions"].items():
        parsed.append((action_id, body))
    parsed.sort(key=lambda item: item[0])

    alias_rows = []
    for index, (action_id, body) in enumerate(parsed):
        stem = snake(action_id)
        emit_string_array(lines, stem + "_source", body["source"])
        emit_string_array(lines, stem + "_defaults", body.get("default", []))
        emit_string_array(lines, stem + "_aliases", body.get("aliases", []))
        for alias in body.get("aliases", []):
            alias_rows.append((alias, index))
        hacks = body.get("hacks", {})
        for number, (hack_id, change) in enumerate(hacks.items()):
            emit_string_array(lines, f"{stem}_hack_{number}_defaults", change.get("default", []))
        if hacks:
            lines.append(f"constexpr HackChange {stem}_hacks[]{{\n")
            for number, (hack_id, change) in enumerate(hacks.items()):
                sets_default = "default" in change
                sets_when = "when" in change
                when_mask = bits(change.get("when", []), condition_index) if sets_when else 0
                default_span = span_of(f"{stem}_hack_{number}_defaults" if change.get("default")
                                        else None)
                lines.append("    {" + ", ".join([
                    cxx_string(hack_id), bool_of(sets_default), default_span, bool_of(sets_when),
                    f"uint32_t{{{when_mask}}}",
                ]) + "},\n")
            lines.append("};\n")
    alias_rows.sort(key=lambda item: item[0])
    if alias_rows:
        lines.append("constexpr AliasRef k_alias_rows[]{\n")
        for alias, index in alias_rows:
            lines.append(f"    {{{cxx_string(alias)}, uint16_t{{{index}}}}},\n")
        lines.append("};\n")
        lines.append("constexpr std::span<const AliasRef> k_aliases{k_alias_rows};\n\n")
    else:
        lines.append("constexpr std::span<const AliasRef> k_aliases{};\n\n")

    lines.append("constexpr Action k_actions[]{\n")
    for action_id, body in parsed:
        stem = snake(action_id)
        hacks = body.get("hacks", {})
        hack_span = (f"std::span<const HackChange>({stem}_hacks)" if hacks
                     else "std::span<const HackChange>{}")
        left = body.get("left-click-default")
        lines.append("    {" + ", ".join([
            cxx_string(action_id),
            cxx_string(body["area"]),
            f"uint16_t{{{body['order']}}}",
            f"uint32_t{{{bits(body['context'], context_index)}}}",
            f"uint32_t{{{bits(body.get('when', []), condition_index)}}}",
            kind_of(body["kind"]),
            by_of(body.get("by")),
            span_of(stem + "_source"),
            span_of(stem + "_defaults" if body.get("default") else None),
            f"Words{{{cxx_string(body['words']['name'])}, {cxx_string(body['words']['description'])}}}",
            span_of(stem + "_aliases" if body.get("aliases") else None),
            cxx_string(body["replaces"]) if "replaces" in body else "std::string_view{}",
            bool_of(body.get("fixed") is True),
            bool_of(body.get("latchable") is True),
            bool_of(body.get("confirmable") is True),
            bool_of(body.get("repeatable") is True),
            hack_span,
            cxx_string(left) if isinstance(left, str) else "std::string_view{}",
            target_of(body.get("target")),
            cxx_string(body["gadget"]) if "gadget" in body else "std::string_view{}",
            cxx_string(body["pad"]) if "pad" in body else "std::string_view{}",
            cxx_string(body["touch"]) if "touch" in body else "std::string_view{}",
        ]) + "},\n")
    lines.append("};\n")
    return "".join(lines)


def generate():
    reg = oamod_yaml.load_file(REGISTRY)
    hack_ids, pads, touch_enums = load_references()
    problems = check_registry(reg, hack_ids, pads, touch_enums)
    if problems:
        raise RegistryError(problems)
    return {TABLE: generate_text(reg)}


