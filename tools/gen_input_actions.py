class RegistryError(Exception):
    def __init__(self, problems):
        self.problems = problems
        super().__init__("\n".join(problems))


def is_int(value):
    return isinstance(value, int) and not isinstance(value, bool)


def catalogue_safe(text):
    if not isinstance(text, str) or text != text.strip():
        return False
    return "\n" not in text and "\r" not in text and "]" not in text and "//" not in text \
        and "/*" not in text


def add(problems, owner, field, message):
    problems.append(f"{owner}: {field}: {message}")


def as_strings(value):
    return isinstance(value, list) and all(isinstance(item, str) for item in value)


# --------------------------------------------------------------------------------------- chords
def chord_parts(text):
    """(modifiers, trigger class, trigger, gesture, error).

    trigger class is character, position, named, mouse, wheel, pad or modifier.
    """
    if not isinstance(text, str) or text == "":
        return None, None, None, None, "the chord is empty"
    gesture = None
    body = text
    if ":" in text:
        body, gesture = text.rsplit(":", 1)
        if gesture not in GESTURES:
            return None, None, None, None, "a gesture the grammar does not name"
    parts = body.split("+")
    if any(part == "" for part in parts):
        return None, None, None, None, "the chord has an empty part"
    if len(parts) == 1 and parts[0] in MODIFIERS:
        if gesture is not None:
            return None, None, None, None, "a gesture on a modifier alone"
        return (), "modifier", parts[0], None, None
    trigger = parts[-1]
    modifiers = parts[:-1]
    if trigger in MODIFIERS or any(part not in MODIFIERS for part in modifiers):
        return None, None, None, None, "a chord needs a trigger"
    if len(modifiers) != len(set(modifiers)):
        return None, None, None, None, "modifier twice"
    order = [MODIFIERS.index(part) for part in modifiers]
    if order != sorted(order):
        return None, None, None, None, "modifiers are out of order"
    kind = trigger_class(trigger)
    if kind is None:
        return None, None, None, None, "not a trigger"
    if gesture is not None and kind in ("wheel", "modifier"):
        return None, None, None, None, "a gesture on a wheel or a modifier alone"
    return tuple(modifiers), kind, trigger, gesture, None


def trigger_class(trigger):
    if trigger in MOUSE_BUTTONS:
        return "mouse"
    if trigger in WHEEL_TURNS:
        return "wheel"
    if trigger in NAMED_KEYS:
        return "named"
    if trigger.startswith("Pad.") and re.fullmatch(r"[A-Z][A-Za-z0-9]*", trigger[4:]):
        return "pad"
    if trigger.startswith("@") and re.fullmatch(r"[A-Z][A-Za-z0-9]*", trigger[1:]):
        return "position"
    if len(trigger) == 1 and 0x21 <= ord(trigger) <= 0x7E:
        if trigger.isalpha() and not trigger.isupper():
            return None
        return "character"
    return None


def check_chord(text, kind, by, problems, owner, field):
    modifiers, trigger, _token, _gesture, error = chord_parts(text)
    if error is not None:
        add(problems, owner, field, error)
        return
    if trigger == "modifier" and kind != "modifier":
        add(problems, owner, field, "a modifier alone on a kind other than modifier")
    if trigger == "mouse" and kind != "pointer":
        add(problems, owner, field, "a mouse button on a kind other than pointer")
    if trigger == "wheel" and kind in ("press", "hold", "modifier"):
        add(problems, owner, field, "a wheel turn on a press, hold or modifier")
    if trigger in ("character", "position") and by not in BYS:
        add(problems, owner, field, "by is missing")
    if by == "letter" and trigger == "position":
        add(problems, owner, field, "by letter default written as a position")
    if by == "place" and trigger == "character":
        add(problems, owner, field, "by place default written as a character")


def check_defaults(chords, kind, by, problems, owner, field):
    if not as_strings(chords):
        add(problems, owner, field, "defaults are not a list of chords")
        return
    if len(chords) > DEFAULT_LIMIT:
        add(problems, owner, field, "more than four defaults")
    if len(chords) != len(set(chords)):
        add(problems, owner, field, "one default twice")
    if not chords:
        add(problems, owner, field, "defaults are empty")
    for chord in chords:
        check_chord(chord, kind, by, problems, owner, field)


# --------------------------------------------------------------------------------------- enums
def enum_block(text, name):
    match = re.search(r"enum class " + name + r"\b[^{]*\{", text)
    if match is None:
        raise RegistryError([f"registry: field: enum class {name} was not found"])
    end = text.find("};", match.end())
    if end < 0:
        raise RegistryError([f"registry: field: enum class {name} does not close"])
    body = re.sub(r"//.*", "", text[match.end():end])
    return set(re.findall(r"\b([A-Za-z_][A-Za-z0-9_]*)\b", body))


def load_references():
    hacks = oamod_yaml.load_file(HACK_REGISTRY)
    entries = hacks.get("entries", {}) if isinstance(hacks, dict) else {}
    hack_ids = {entry_id for entry_id, entry in entries.items()
                if isinstance(entry, dict) and entry.get("kind") == "hack"}
    pad = enum_block(PAD_HEADER.read_text(encoding="utf-8"), "Action")
    touch = TOUCH_HEADER.read_text(encoding="utf-8")
    return hack_ids, pad, {
        "latch": enum_block(touch, "Latch"),
        "radial": enum_block(touch, "RadialItem"),
        "select": enum_block(touch, "SelectItem"),
    }


# ----------------------------------------------------------------------------------- structure
def check_top(reg, problems):
    if not isinstance(reg, dict):
        add(problems, "registry", "top-level", "the registry is not a mapping")
        return False
    for key in reg:
        if key not in ("input-actions", "contexts", "conditions", "areas", "families", "actions"):
            add(problems, "registry", "top-level", f"{key} is not a top-level key")
    version = reg.get("input-actions", None)
    if isinstance(version, bool) or version != 1:
        add(problems, "registry", "top-level", "input-actions is not 1")
    return True


def check_contexts(reg, problems):
    raw = reg.get("contexts") if isinstance(reg, dict) else None
    if not isinstance(raw, dict):
        add(problems, "registry", "field", "contexts is missing")
        return {}
    found = []
    for name, body in raw.items():
        if not isinstance(body, dict):
            add(problems, name, "field", "the context is not a mapping")
            continue
        for key in body:
            if key not in ("parent", "overlay", "title"):
                add(problems, name, "field", f"{key} is not a field")
        parent = body.get("parent", "")
        if parent is not None and not isinstance(parent, str):
            add(problems, name, "field", "parent is not a context")
            parent = None
        overlay = body.get("overlay", None)
        if not isinstance(overlay, bool):
            add(problems, name, "field", "overlay is not a boolean")
            overlay = False
        title = body.get("title", "")
        if not catalogue_safe(title) or title == "":
            add(problems, name, "field", "the title cannot be a catalogue section")
        found.append((name, parent, overlay, title))
    if found != CONTEXTS:
        for (name, parent, _overlay, _title), expected in zip(found, CONTEXTS):
            if name == expected[0] and parent != expected[1]:
                add(problems, "registry", "tree",
                    f"{name} parent {parent} is not {expected[1]}")
                break
        else:
            add(problems, "registry", "tree", "the context tree is not the catalogue's")
    parents = {}
    names = {name for name, _parent, _overlay, _title in found}
    for name, parent, _overlay, _title in found:
        if parent is not None and parent not in names:
            add(problems, "registry", "tree", f"{name} parent {parent} is not a context")
            parents[name] = None
        else:
            parents[name] = parent
    for name in names:
        seen = set()
        current = name
        while current is not None:
            if current in seen:
                add(problems, "registry", "tree", f"{name} cycles")
                break
            seen.add(current)
            current = parents.get(current)
        else:
            if "global" not in seen:
                add(problems, "registry", "tree", f"{name} does not reach global")
    return {name: index for index, (name, _parent, _overlay, _title) in enumerate(found)}


def check_conditions(reg, problems):
    raw = reg.get("conditions") if isinstance(reg, dict) else None
    if not isinstance(raw, dict):
        add(problems, "registry", "field", "conditions is missing")
        return {}
    for key in raw:
        if key not in ("names", "exclusive"):
            add(problems, "registry", "field", f"conditions.{key} is not a field")
    names = raw.get("names")
    if names != CONDITION_NAMES:
        add(problems, "registry", "field", "conditions are not the eight, in order")
        names = names if as_strings(names) else []
    if raw.get("exclusive") != EXCLUSIVE_PAIRS:
        add(problems, "registry", "exclusive", "the exclusive pairs are not the two named")
    return {name: index for index, name in enumerate(names)}


def check_areas(reg, problems):
    raw = reg.get("areas") if isinstance(reg, dict) else None
    if not isinstance(raw, dict):
        add(problems, "registry", "field", "areas is missing")
        return {}
    expected = {name: (index, title) for index, (name, title) in enumerate(AREAS, start=1)}
    if list(raw) != [name for name, _title in AREAS]:
        add(problems, "registry", "field", "the areas are not the catalogue's, in order")
    for name, body in raw.items():
        if not isinstance(body, dict):
            add(problems, name, "field", "the area is not a mapping")
            continue
        for key in body:
            if key not in ("order", "title"):
                add(problems, name, "field", f"{key} is not a field")
        order = body.get("order")
        title = body.get("title", "")
        want = expected.get(name)
        if want is None or order != want[0] or title != want[1]:
            add(problems, name, "order", "the area's order or title differs from the catalogue")
        if not catalogue_safe(title) or title == "":
            add(problems, name, "field", "the title cannot be a catalogue section")
    return {name: index for index, name in enumerate(raw)}


def check_name_list(value, known, problems, owner, field):
    if not as_strings(value) or not value:
        add(problems, owner, field, f"{field} is not a list of names")
        return []
    if len(value) != len(set(value)):
        add(problems, owner, field, f"{field} names one twice")
    for name in value:
        if name not in known:
            add(problems, owner, field, f"{name} is not a {field}")
    return value


def exclusive_together(names):
    held = set(names)
    for pair in EXCLUSIVE_PAIRS:
        if pair[0] in held and pair[1] in held:
            return pair
    return None


def check_when(value, problems, owner, field):
    if not as_strings(value):
        add(problems, owner, field, "when is not a list of conditions")
        return
    if len(value) != len(set(value)):
        add(problems, owner, field, "when names one condition twice")
    for name in value:
        if name not in CONDITION_NAMES:
            add(problems, owner, field, f"{name} is not a condition")
    pair = exclusive_together(value)
    if pair is not None:
        add(problems, owner, field, f"exclusive conditions {pair[0]} and {pair[1]}")


def check_source(value, hack_ids, problems, owner):
    if not as_strings(value) or not value:
        add(problems, owner, "source", "source is not a list")
        return []
    for item in value:
        if item not in PLAIN_SOURCES and item not in hack_ids:
            add(problems, owner, "source", f"{item} is not a source")
    return value


def check_families(reg, areas, contexts, hack_ids, problems):
    raw = reg.get("families") if isinstance(reg, dict) else None
    if not isinstance(raw, dict):
        add(problems, "registry", "field", "families is missing")
        return
    if list(raw) != list(FAMILIES):
        add(problems, "registry", "field", "families are not gui and select.category")
    for family_id, body in raw.items():
        if family_id not in FAMILIES:
            add(problems, family_id, "id", "is not a load-time family")
        if not isinstance(body, dict):
            add(problems, family_id, "field", "the family is not a mapping")
            continue
        for key in body:
            if key not in FAMILY_FIELDS:
                add(problems, family_id, "field", f"{key} is not a field")
        for key in ("area", "context", "kind", "by", "source"):
            if key not in body:
                add(problems, family_id, "field", f"{key} is missing")
        if body.get("area") not in areas:
            add(problems, family_id, "area", "the area is not declared")
        if "context" in body:
            check_name_list(body["context"], contexts, problems, family_id, "context")
        if body.get("kind") not in KINDS:
            add(problems, family_id, "kind", "the kind is not one of the six")
        if body.get("by") not in BYS:
            add(problems, family_id, "by", "by is not letter or place")
        if "source" in body:
            check_source(body["source"], hack_ids, problems, family_id)
        template = body.get("default-template", None)
        if template is not None and (not isinstance(template, str) or template == ""
                                      or not catalogue_safe(template)):
            add(problems, family_id, "field", "default-template cannot be kept as text")
        panel = body.get("order-panel", None)
        if panel is not None:
            if not isinstance(panel, dict):
                add(problems, family_id, "field", "order-panel is not a mapping")
            else:
                for key in panel:
                    if key not in ("area", "context"):
                        add(problems, family_id, "field", f"order-panel.{key} is not a field")
                if panel.get("area") not in areas:
                    add(problems, family_id, "area", "the order-panel area is not declared")
                if "context" in panel:
                    check_name_list(panel["context"], contexts, problems, family_id, "context")


def check_id(action_id, problems, seen):
    if not isinstance(action_id, str) or not ENTRY_ID.fullmatch(action_id) \
            or len(action_id.encode()) > ID_LIMIT:
        add(problems, action_id, "id", "the id is not kebab words joined by dots")
    if action_id.startswith("gui.") or action_id.startswith("select.category-"):
        add(problems, action_id, "id", "made at load")
    prefix = action_id.split(".", 1)[0]
    if prefix not in PREFIXES:
        add(problems, action_id, "id", "the prefix is not in the catalogue")
    if action_id in seen:
        add(problems, action_id, "id", "equals another id or alias")
    seen.add(action_id)


def check_words(body, problems, owner):
    words = body.get("words")
    if not isinstance(words, dict):
        add(problems, owner, "field", "words is missing")
        return "", ""
    for key in words:
        if key not in ("name", "description"):
            add(problems, owner, "field", f"words.{key} is not a field")
    name = words.get("name", "")
    description = words.get("description", "")
    if not isinstance(name, str) or name == "" or len(name.encode()) > NAME_LIMIT \
            or not catalogue_safe(name):
        add(problems, owner, "words", "name is empty, too long or not a catalogue section")
    if not isinstance(description, str) or description == "" \
            or len(description.encode()) > DESCRIPTION_LIMIT or not catalogue_safe(description):
        add(problems, owner, "words", "description is empty, too long or not a catalogue section")
    return name if isinstance(name, str) else "", description if isinstance(description, str) else ""


def check_touch(value, touch_enums, problems, owner):
    if not isinstance(value, str):
        add(problems, owner, "touch", "touch is not a name")
        return
    prefix, dot, enumerator = value.partition(".")
    if dot != "." or prefix not in touch_enums or enumerator not in touch_enums[prefix]:
        add(problems, owner, "touch", f"{value} is not a touch action")


def check_flags(body, kind, problems, owner):
    for flag in ("fixed", "latchable", "confirmable", "repeatable"):
        if flag not in body:
            continue
        if not isinstance(body[flag], bool):
            add(problems, owner, flag, f"{flag} is not a boolean")
    if body.get("fixed") is True and body.get("default") != ["Escape"]:
        add(problems, owner, "fixed", "the one fixed job is Escape")
    if body.get("latchable") is True and kind not in ("hold", "modifier"):
        add(problems, owner, "latchable", "latchable is only for a hold or a modifier")
    if body.get("repeatable") is True and kind != "repeat":
        add(problems, owner, "repeatable", "repeatable is only for a repeat action")


def check_hacks(body, kind, by, hack_ids, problems, owner):
    hacks = body.get("hacks")
    if hacks is None:
        return
    if not isinstance(hacks, dict):
        add(problems, owner, "hacks", "hacks is not a mapping")
        return
    setting_default = 0
    for hack_id, change in hacks.items():
        if hack_id not in hack_ids:
            add(problems, owner, "hacks", f"{hack_id} is not a hack id")
        if not isinstance(change, dict):
            add(problems, owner, "hacks", f"{hack_id} is not a mapping")
            continue
        for key in change:
            if key not in ("default", "when"):
                add(problems, owner, "hacks", f"{hack_id}.{key} is not a field")
        if "default" not in change and "when" not in change:
            add(problems, owner, "hacks", f"{hack_id} sets neither default nor when")
        if "default" in change:
            setting_default += 1
            check_defaults(change["default"], kind, by, problems, owner, "default")
        if "when" in change:
            check_when(change["when"], problems, owner, "hacks")
    if setting_default > 1:
        add(problems, owner, "hacks", "two entries set default")


def parse_action(action_id, body, areas, contexts, hack_ids, pads, touch_enums, problems, seen):
    check_id(action_id, problems, seen)
    if not isinstance(body, dict):
        add(problems, action_id, "field", "the entry is not a mapping")
        return None
    for key in body:
        if key not in ACTION_FIELDS:
            add(problems, action_id, "field", f"{key} is not a field")
    for key in REQUIRED_FIELDS:
        if key not in body:
            add(problems, action_id, "field", f"{key} is missing")
    area = body.get("area")
    if area not in areas:
        add(problems, action_id, "area", f"{area} is not an area")
    order = body.get("order")
    if not is_int(order) or order < 1 or order > 65535:
        add(problems, action_id, "order", "order is not a positive integer")
        order = None
    context = []
    if "context" in body:
        context = check_name_list(body["context"], contexts, problems, action_id, "context")
    if "when" in body:
        check_when(body["when"], problems, action_id, "when")
    kind = body.get("kind")
    if kind not in KINDS:
        add(problems, action_id, "kind", "the kind is not one of the six")
    by = body.get("by", None)
    if "by" in body and by not in BYS:
        add(problems, action_id, "by", "by is not letter or place")
    source = check_source(body.get("source", None), hack_ids, problems, action_id) \
        if "source" in body else []
    if "default" in body:
        check_defaults(body["default"], kind, by, problems, action_id, "default")
    name, description = check_words(body, problems, action_id)
    aliases = []
    if "aliases" in body:
        if not as_strings(body["aliases"]) or not body["aliases"]:
            add(problems, action_id, "id", "aliases are not a list of ids")
        else:
            for alias in body["aliases"]:
                if not ENTRY_ID.fullmatch(alias) or len(alias.encode()) > ID_LIMIT:
                    add(problems, action_id, "id", f"alias {alias} is not an id")
                elif alias in seen:
                    add(problems, action_id, "id", f"alias {alias} equals another id or alias")
                else:
                    seen.add(alias)
                    aliases.append(alias)
    check_flags(body, kind, problems, action_id)
    check_hacks(body, kind, by, hack_ids, problems, action_id)
    if "left-click-default" in body:
        if kind != "pointer":
            add(problems, action_id, "left-click-default", "only a pointer action has one")
        elif not isinstance(body["left-click-default"], str):
            add(problems, action_id, "left-click-default", "is not a chord")
        else:
            check_chord(body["left-click-default"], kind, by, problems, action_id,
                        "left-click-default")
    if kind in ("pointer", "wheel"):
        if "target" not in body:
            add(problems, action_id, "target", f"a {kind} action needs a target")
        elif body["target"] not in TARGETS:
            add(problems, action_id, "target", f"{body['target']} is not a target")
    elif "target" in body:
        add(problems, action_id, "target", f"a {kind} action has a target")
    gadget = body.get("gadget", None)
    if gadget is not None and (not isinstance(gadget, str) or re.fullmatch(r"[A-Z]+", gadget) is None):
        add(problems, action_id, "gadget", "a gadget is upper-case letters")
        gadget = None
    if "pad" in body and body["pad"] not in pads:
        add(problems, action_id, "pad", f"{body['pad']} is not an Action enumerator")
    if "touch" in body:
        check_touch(body["touch"], touch_enums, problems, action_id)
    return {
        "id": action_id,
        "area": area if isinstance(area, str) else "",
        "order": order,
        "context": context,
        "when": body.get("when", []) if as_strings(body.get("when", [])) else [],
        "kind": kind if kind in KINDS else "press",
        "by": by if by in BYS else None,
        "source": source,
        "default": body.get("default", []) if as_strings(body.get("default", [])) else [],
        "name": name,
        "description": description,
        "aliases": aliases,
        "replaces": body.get("replaces", None),
        "fixed": body.get("fixed") is True,
        "latchable": body.get("latchable") is True,
        "confirmable": body.get("confirmable") is True,
        "repeatable": body.get("repeatable") is True,
        "hacks": body.get("hacks") if isinstance(body.get("hacks"), dict) else {},
        "left": body.get("left-click-default") if isinstance(body.get("left-click-default"), str)
        else None,
        "target": body.get("target") if body.get("target") in TARGETS else None,
        "gadget": gadget if isinstance(gadget, str) else None,
        "pad": body.get("pad") if isinstance(body.get("pad"), str) else None,
        "touch": body.get("touch") if isinstance(body.get("touch"), str) else None,
        "raw": body,
    }


def check_cross(parsed, hack_ids, problems):
    by_id = {row["id"]: row for row in parsed}
    orders = {}
    gadgets = {}
    for row in parsed:
        if row["order"] is not None and row["area"]:
            slot = (row["area"], row["order"])
            if slot in orders:
                add(problems, row["id"], "order",
                    f"order {row['order']} is already used in {row['area']}")
            else:
                orders[slot] = row["id"]
        if row["gadget"]:
            if row["gadget"] in gadgets:
                add(problems, row["id"], "gadget",
                    f"{row['gadget']} is shared with {gadgets[row['gadget']]}")
            else:
                gadgets[row["gadget"]] = row["id"]
        if "replaces" not in row["raw"]:
            continue
        replacement = row["raw"]["replaces"]
        if not isinstance(replacement, str):
            add(problems, row["id"], "replaces", "replaces is not an id")
            continue
        if "default" in row["raw"]:
            add(problems, row["id"], "replaces", "replaces is set together with a default")
        sources = row["raw"].get("source", [])
        if not as_strings(sources) or not sources \
                or any(item not in hack_ids for item in sources):
            add(problems, row["id"], "replaces", "sources are not all hack ids")
        base = by_id.get(replacement)
        if base is None:
            add(problems, row["id"], "replaces", f"{replacement} is not a base action")
            continue
        base_sources = base["raw"].get("source", [])
        if as_strings(base_sources) and base_sources \
                and all(item in hack_ids for item in base_sources):
            add(problems, row["id"], "replaces", f"{replacement} is not a base action")
        shared = set(row["context"]) & set(base["context"])
        if not shared:
            add(problems, row["id"], "replaces", f"{replacement} shares no context")


def check_registry(reg, hack_ids, pads, touch_enums):
    """Every problem in the registry. Collects them all; it does not stop at the first."""
    problems = []
    if not check_top(reg, problems):
        return problems
    contexts = check_contexts(reg, problems)
    check_conditions(reg, problems)
    areas = check_areas(reg, problems)
    check_families(reg, areas, contexts, hack_ids, problems)
    raw = reg.get("actions")
    if not isinstance(raw, dict):
        add(problems, "registry", "field", "actions is missing")
        return problems
    seen = set()
    parsed = []
    for action_id, body in raw.items():
        row = parse_action(action_id, body, areas, contexts, hack_ids, pads, touch_enums,
                           problems, seen)
        if row is not None:
            parsed.append(row)
    check_cross(parsed, hack_ids, problems)
    return problems


