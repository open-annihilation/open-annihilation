"""Generate the action table from the action registry.

Reads src/data/input-actions/registry/actions.yaml, checks that every action,
context, condition, area and family agrees with the catalogue's rules, and
writes:

  src/data/input-actions/src/actions.inc
      the registry as constant C++ tables, which oa-data-input-actions reads.

Defaults stay text. The C++ grammar that parses a chord is a later ticket's.

  gen_input_actions.py              write the table
  gen_input_actions.py --check      write nothing; exit 1 when the table differs
                                    or the registry breaks a rule
  gen_input_actions.py --self-test  plant one break of each rule
  gen_input_actions.py --list       print one action id a line
"""

